def get_subtitle_code(key: str) -> tuple[str, str]:
    """Return ``(iso639_code, display_name)`` for a subtitle language *key*.

    Handles case-fixing for keys like ``zh-hans`` → ``zh-Hans``.
    """
    m = _NON_CAPS_RE.search(key)
    if m:
        key = key.replace(m.group(), m.group().upper())
    return _SUBTITLE_MAP.get(key, ("und", "Undetermined"))


