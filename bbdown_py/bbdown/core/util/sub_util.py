def _format_time(sec: float) -> str:
    """Format seconds to ``hh:mm:ss,fff`` for SRT."""
    td = timedelta(seconds=sec)
    total_seconds = int(td.total_seconds())
    hours = total_seconds // 3600
    minutes = (total_seconds % 3600) // 60
    secs = total_seconds % 60
    millis = int(td.microseconds / 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"


def _convert_sub_from_json(json_string: str) -> str:
    """Convert Bilibili JSON subtitle format to SRT text."""
    data = json.loads(json_string)
    body = data["body"]
    lines: list[str] = []
    for i, line in enumerate(body, start=1):
        lines.append(str(i))
        from_time = line.get("from", 0.0)
        to_time = line["to"]
        lines.append(f"{_format_time(from_time)} --> {_format_time(to_time)}")
        content = line.get("content", "")
        lines.append(content)
        lines.append("")
    return "\n".join(lines) + "\n"
