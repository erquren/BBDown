async def get_subtitles(
    aid: str,
    cid: str,
    ep_id: str,
    index: int,
    intl: bool,
) -> list[Subtitle]:
    """Fetch available subtitles for a video, trying multiple APIs in order."""
    subtitles: list[Subtitle] | None = None
    if intl:
        subtitles = (
            await _get_intl_subtitles_from_api1(aid, cid, ep_id, index)
            or await _get_intl_subtitles_from_api2(aid, cid, ep_id, index)
        )
    else:
        if config.COOKIE == "":
            subtitles = await _get_subtitles_from_api3(aid, cid, ep_id, index)
        else:
            subtitles = (
                await _get_subtitles_from_api2(aid, cid, ep_id, index)
                or await _get_subtitles_from_api1(aid, cid, ep_id, index)
                or await _get_subtitles_from_api3(aid, cid, ep_id, index)
            )

    if subtitles is None:
        return []

    # Fix protocol for URLs starting with "//"
    for item in subtitles:
        if item.url.startswith("//"):
            item.url = "https:" + item.url

    return subtitles


async def save_subtitle(url: str, path: str) -> None:
    """Download a subtitle and save it. Convert JSON→SRT when *path* ends with ``.srt``."""
    raw = await get_web_source(url)
    if path.endswith(".srt"):
        text = _convert_sub_from_json(raw)
    else:
        text = raw
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


