def _get_payload(aid: int, cid: int) -> bytes:
    """Build gRPC payload for DmView request."""
    obj = DmViewReq()
    obj.pid = aid
    obj.oid = cid
    obj.type = 1
    obj.spmid = "main.ugc-video-detail.0.0"
    return app_helper.pack_message(obj.SerializeToString())


async def _get_subtitles_from_api3(
    aid: str, cid: str, ep_id: str, index: int
) -> Optional[list[Subtitle]]:
    """gRPC API – ``bilibili.community.service.dm.v1.DM/DmView``."""
    try:
        subtitles: list[Subtitle] = []
        api = "https://app.biliapi.net/bilibili.community.service.dm.v1.DM/DmView"
        data = _get_payload(int(aid), int(cid))
        raw = await get_post_response(api, data)
        body = app_helper.read_message(raw)
        resp = DmViewReply()
        resp.ParseFromString(body)
        if resp.subtitle and resp.subtitle.subtitles:
            for item in resp.subtitle.subtitles:
                subtitles.append(
                    Subtitle(
                        lan=item.lan,
                        url=item.subtitle_url,
                        path=f"{aid}/{aid}.{cid}.{item.lan}.srt",
                    )
                )
        if any(not s.url for s in subtitles):
            raise ValueError("Bad url")
        return subtitles
    except Exception:
        return None


