async def _get_intl_subtitles_from_api1(
    aid: str, cid: str, ep_id: str, index: int
) -> Optional[list[Subtitle]]:
    """International API 1 – ``/intl/gateway/web/v2/subtitle``."""
    try:
        subtitles: list[Subtitle] = []
        host = (
            "api.biliintl.com"
            if config.EPHOST == "api.bilibili.com"
            else config.EPHOST
        )
        api = f"https://{host}/intl/gateway/web/v2/subtitle?episode_id={ep_id}"
        raw = await get_web_source(api)
        data = json.loads(raw)
        for sub in data["data"]["subtitles"]:
            lan = sub["lang_key"]
            url = sub["url"]
            ext = ".srt" if ".json" in url else ".ass"
            subtitle = Subtitle(
                lan=lan,
                url=url,
                path=f"{aid}/{aid}.{cid}.{lan}{ext}",
            )
            if any(not s.url for s in subtitles):
                raise ValueError("Bad url")
            subtitles.append(subtitle)
        return subtitles
    except Exception:
        return None


async def _get_intl_subtitles_from_api2(
    aid: str, cid: str, ep_id: str, index: int
) -> Optional[list[Subtitle]]:
    """International API 2 – ``/intl/gateway/v2/ogv/view/app/season``."""
    try:
        subtitles: list[Subtitle] = []
        host = (
            "api.bilibili.tv"
            if config.HOST == "api.bilibili.com"
            else config.HOST
        )
        api = (
            f"https://{host}/intl/gateway/v2/ogv/view/app/season"
            f"?ep_id={ep_id}&platform=android&s_locale=zh_SG"
        )
        if config.TOKEN:
            api += f"&access_key={config.TOKEN}"
        raw = await get_web_source(api)
        data = json.loads(raw)
        episodes = data["result"]["modules"][0]["data"]["episodes"]
        for sub in episodes[index - 1]["subtitles"]:
            lan = sub["key"]
            url = sub["url"].replace("\\\\/", "/")
            ext = ".srt" if ".json" in url else ".ass"
            subtitle = Subtitle(
                lan=lan,
                url=url,
                path=f"{aid}/{aid}.{cid}.{lan}{ext}",
            )
            if any(not s.url for s in subtitles):
                raise ValueError("Bad url")
            subtitles.append(subtitle)
        return subtitles
    except Exception:
        return None


